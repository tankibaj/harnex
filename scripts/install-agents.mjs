#!/usr/bin/env node
// Installs harnex's sub-agents for tools whose plugins can't ship them.
// Claude Code needs none of this: its plugin loads agents/ itself.
//
//   node scripts/install-agents.mjs --codex       ~/.codex/agents/harnex-<name>.toml
//   node scripts/install-agents.mjs --opencode    ~/.config/opencode/agents/harnex-<name>.md
//   node scripts/install-agents.mjs --all         both
//   add --uninstall to remove what it installed
//
// Each file is generated from agents/<name>.md and marked; a file without the
// mark is never overwritten or removed. Without these agents the orchestrator
// runs each phase itself (skills/harnex/SKILL.md).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MARK = 'Generated by harnex scripts/install-agents.mjs';
const CAPS = ['edit', 'bash', 'webfetch', 'task', 'skill'];
const TOOL_CAP = {
  Read: 'read', Grep: 'read', Glob: 'read', Bash: 'bash', Write: 'edit', Edit: 'edit',
  NotebookEdit: 'edit', WebFetch: 'webfetch', WebSearch: 'webfetch', Agent: 'task', Skill: 'skill',
};
// They write test artifacts, caches, screenshots: read-only would block them,
// in Codex (sandbox) and OpenCode (permissions) alike.
const CODEX_WRITE = new Set(['suite-runner', 'validator', 'ui-ux-reviewer', 'qa']);

function parse(file) {
  const text = fs.readFileSync(file, 'utf8');
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const data = {};
  const lines = m[1].split('\n');
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([A-Za-z]+):\s*(.*)$/);
    if (!kv) continue;
    let [, key, value] = kv;
    if (value === '>' || value === '>-') {
      const block = [];
      while (i + 1 < lines.length && /^\s/.test(lines[i + 1])) block.push(lines[++i].trim());
      value = block.join(' ');
    }
    data[key] = value.replace(/^"(.*)"$/, '$1');
  }
  const list = (v) => (v ? v.split(',').map((s) => s.trim()).filter(Boolean) : null);
  return { name: data.name, description: data.description, tools: list(data.tools),
    disallowed: list(data.disallowedTools), body: text.slice(m[0].length) };
}

function denied(a) {
  if (a.tools) return CAPS.filter((c) => !a.tools.some((t) => TOOL_CAP[t] === c));
  if (a.disallowed) return CAPS.filter((c) => a.disallowed.some((t) => TOOL_CAP[t] === c));
  return [];
}

const toml = (s) => JSON.stringify(s);
const tomlBlock = (s) => (s.includes("'''") ? toml(s) : `'''\n${s}'''`);

const TARGETS = {
  codex: {
    dir: () => path.join(os.homedir(), '.codex', 'agents'),
    file: (n) => `harnex-${n}.toml`,
    render: (a) => [
      `# ${MARK} from agents/${a.name}.md`,
      `name = ${toml(`harnex-${a.name}`)}`,
      `description = ${toml(a.description)}`,
      `sandbox_mode = ${toml(CODEX_WRITE.has(a.name) || !denied(a).includes('edit') ? 'workspace-write' : 'read-only')}`,
      `developer_instructions = ${tomlBlock(a.body)}`,
      '',
    ].join('\n'),
  },
  opencode: {
    dir: () => path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'), 'opencode', 'agents'),
    file: (n) => `harnex-${n}.md`,
    render: (a) => {
      const fm = [`description: ${JSON.stringify(a.description)}`, 'mode: subagent'];
      // Same rule as Codex: agents that write artifacts keep edit access.
      const d = denied(a).filter((c) => !(c === 'edit' && CODEX_WRITE.has(a.name)));
      if (d.length) fm.push('permission:', ...d.map((c) => `  ${c}: deny`));
      return `---\n${fm.join('\n')}\n---\n<!-- ${MARK} from agents/${a.name}.md -->\n${a.body}`;
    },
  },
};

function main(argv) {
  const uninstall = argv.includes('--uninstall');
  const picked = argv.includes('--all') ? ['codex', 'opencode'] : ['codex', 'opencode'].filter((t) => argv.includes(`--${t}`));
  if (!picked.length) {
    console.error('usage: install-agents.mjs --codex | --opencode | --all [--uninstall]');
    return 2;
  }
  const agents = fs.readdirSync(path.join(ROOT, 'agents')).filter((f) => f.endsWith('.md')).sort()
    .map((f) => parse(path.join(ROOT, 'agents', f)));
  let status = 0;
  for (const t of picked) {
    const { dir, file, render } = TARGETS[t];
    const d = dir();
    fs.mkdirSync(d, { recursive: true });
    for (const a of agents) {
      const target = path.join(d, file(a.name));
      const ours = !fs.existsSync(target) || fs.readFileSync(target, 'utf8').includes(MARK);
      if (!ours) {
        console.error(`skip ${target}: not written by harnex`);
        status = 1;
        continue;
      }
      if (uninstall) {
        if (fs.existsSync(target)) { fs.rmSync(target); console.log(`removed ${target}`); }
      } else {
        fs.writeFileSync(target, render(a));
        console.log(`installed ${target}`);
      }
    }
  }
  return status;
}

process.exitCode = main(process.argv.slice(2));
